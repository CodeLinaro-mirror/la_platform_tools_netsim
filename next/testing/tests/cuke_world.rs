/// Cuke: When I add (\d+)
async fn add_step(w: &mut TestWorld, val: i32) {
    w.display += val;
    w.log.push(format!("add {}", val));
}

/// Cuke: Then result is (\d+)
async fn check_step(w: &mut TestWorld, val: i32) {
    // A real test step should panic/assert on failure so the test framework catches
    // it.
    assert_eq!(w.display, val, "Check failed: expected {}, got {}", val, w.display);
    w.log.push(format!("check {}", val));
}

