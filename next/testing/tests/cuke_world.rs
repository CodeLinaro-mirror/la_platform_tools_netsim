/// # Example World
///
/// This is an example of a "World" struct that holds the state for Cuke tests.
/// It demonstrates how to use the `cuke_codegen` macro to automatically
/// generate glue code.
///
/// The `cuke_codegen` tool (invoked via `genrule` in BUILD) parses this file,
/// finds methods commented with `/// Cuke:`, and generates
/// `cuke_world_glue.rs`.
struct TestWorld {
    /// The main display register (accumulator)
    display: i32,
    log: Vec<String>,
    users: std::collections::HashMap<String, i32>,
    tx_power: TxPower,
    enabled: bool,
    temperature: f64,
    /// The memory register (M+, M-, MR, MC)
    memory: i32,
    /// Mock network interface buffer (stores received packets)
    received_packets: Vec<Vec<u8>>,
}

#[derive(Debug, PartialEq, Clone, Copy)]
enum TxPower {
    High,
    Medium,
    Low,
    Ultralow,
}

impl std::str::FromStr for TxPower {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s {
            "High" => Ok(TxPower::High),
            "Medium" => Ok(TxPower::Medium),
            "Low" => Ok(TxPower::Low),
            "Ultralow" => Ok(TxPower::Ultralow),
            _ => Err(format!("Invalid TxPower: {}", s)),
        }
    }
}

impl TestWorld {}

/// Cuke: Given I reset the counter
async fn reset_step(w: &mut TestWorld) {
    w.display = 0;
    w.log.push("reset".to_string());
}

